/* eslint-disable @typescript-eslint/no-require-imports -- CommonJS Node CLI/preload scripts require synchronous project-local modules. */
const path=require('node:path');
const repo=path.resolve(__dirname,'../..');
const work=path.dirname(repo);
process.chdir(work);
const {chromium}=require(path.join(work,'browser-tools/node_modules/playwright-core'));
const fs=require('node:fs'),assert=require('node:assert/strict');
(async()=>{
 const account=JSON.parse(fs.readFileSync('local-test-account.json'));
 const browser=await chromium.launch({executablePath:require('./browser-path.cjs').browserPath(),headless:true});
 const context=await browser.newContext({viewport:{width:1280,height:950},serviceWorkers:'block'});
 const external=[];await context.route('**/*',async r=>{const u=new URL(r.request().url());if(['http:','https:'].includes(u.protocol)&&!['127.0.0.1','localhost'].includes(u.hostname)){external.push('blocked-external');return r.abort();}return r.continue();});
 const page=await context.newPage();page.setDefaultTimeout(20000);page.on('dialog',d=>d.accept());
 const errors=[];page.on('pageerror',()=>errors.push('page-error'));
 await page.goto('http://127.0.0.1:3100/local-test');
 await page.getByLabel('테스트 이메일').fill(account.email);await page.getByLabel('테스트 비밀번호').fill(account.password);
 await page.getByRole('button',{name:'로그인',exact:true}).click();await page.getByRole('status').filter({hasText:'로컬 로그인 완료'}).waitFor();console.log('PASS browser local Auth login');
 await page.goto('http://127.0.0.1:3100/car/123%EA%B0%804567/review');
 await page.locator('textarea').waitFor();
 const text='브라우저 합성 후기: 등록과 수정 그리고 삭제를 로컬 환경에서 확인합니다. '+Date.now();
 const updated=text+' 수정 완료';
 await page.locator('textarea').fill(text);
 await page.getByRole('button',{name:'후기 등록하기',exact:true}).click();
 await page.getByText('차량 이야기가 등록되었어요.',{exact:true}).waitFor();console.log('PASS browser review registration');
 await page.goto('http://127.0.0.1:3100/car/123%EA%B0%804567');
 await page.getByText(text,{exact:true}).waitFor();
 await page.getByText(text,{exact:true}).locator('xpath=ancestor::div[.//button[normalize-space()="수정"]][1]').getByRole('button',{name:'수정',exact:true}).click();
 await page.locator('textarea').waitFor();await page.locator('textarea').fill(updated);
 await page.getByRole('button',{name:'후기 수정하기',exact:true}).click();
 await page.getByText('차량 이야기가 수정되었어요.',{exact:true}).waitFor();console.log('PASS browser review update');
 await page.goto('http://127.0.0.1:3100/car/123%EA%B0%804567');
 await page.getByText(updated,{exact:true}).waitFor();
 await page.getByText(updated,{exact:true}).locator('xpath=ancestor::div[.//button[normalize-space()="삭제"]][1]').getByRole('button',{name:'삭제',exact:true}).click();
 await page.getByText(updated,{exact:true}).waitFor({state:'hidden'});
 console.log('PASS browser review delete');
 fs.mkdirSync('screenshots-sandbox',{recursive:true});await page.screenshot({path:'screenshots-sandbox/review-after-delete.png',fullPage:true});
 await page.goto('http://127.0.0.1:3100/local-test');await page.getByRole('button',{name:'로그아웃',exact:true}).click();await page.getByRole('status').filter({hasText:'로그아웃 완료'}).waitFor();console.log('PASS browser signout');
 assert.equal(errors.length,0);console.log('PASS zero browser page errors; external requests blocked:',external.length);
 await browser.close();
})().catch(e=>{console.error('FAILED browser sandbox:',e.name,e.message?.split('\n')[0]);process.exitCode=1});
